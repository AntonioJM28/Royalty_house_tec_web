CREATE TABLE IF NOT EXISTS usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    correo VARCHAR(254) NOT NULL UNIQUE,
    telefono VARCHAR(30) NOT NULL,
    password_hash VARCHAR(128) NOT NULL,
    rol VARCHAR(20) NOT NULL
        CHECK (rol IN ('CLIENTE', 'RECEPCIONISTA', 'ADMINISTRADOR')),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    acepto_datos BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS recurso (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE,
    tipo VARCHAR(20) NOT NULL
        CHECK (tipo IN ('MESA_NORMAL', 'MESA_VIP', 'SALA_MINICINE')),
    capacidad INTEGER NOT NULL CHECK (capacidad > 0),
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS tarifa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_recurso VARCHAR(20) NOT NULL UNIQUE
        CHECK (tipo_recurso IN ('MESA_NORMAL', 'MESA_VIP', 'SALA_MINICINE')),
    precio_hora NUMERIC(10, 2) NOT NULL CHECK (precio_hora >= 0)
);

CREATE TABLE IF NOT EXISTS horario_atencion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hora_apertura TIME NOT NULL,
    hora_cierre TIME NOT NULL,
    CHECK (hora_apertura < hora_cierre)
);

CREATE TABLE IF NOT EXISTS pelicula (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(200) NOT NULL UNIQUE,
    duracion_min INTEGER NOT NULL CHECK (duracion_min > 0),
    en_cartelera BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS reserva (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(8) NOT NULL UNIQUE,
    usuario_id BIGINT REFERENCES usuario(id) ON DELETE SET NULL,
    nombre_cliente VARCHAR(120) NOT NULL,
    telefono_cliente VARCHAR(30) NOT NULL,
    recurso_id BIGINT NOT NULL REFERENCES recurso(id),
    pelicula_id BIGINT REFERENCES pelicula(id),
    fecha DATE NOT NULL,
    hora_inicio TIME NOT NULL,
    bloques INTEGER NOT NULL CHECK (bloques > 0),
    estado VARCHAR(20) NOT NULL
        CHECK (estado IN ('CONFIRMADA', 'EN_USO', 'FINALIZADA', 'CANCELADA', 'NO_PRESENTADA')),
    hora_entrada TIME,
    hora_salida TIME,
    asistentes INTEGER,
    creada_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (id, recurso_id, fecha)
);

ALTER TABLE reserva ADD COLUMN IF NOT EXISTS asistentes INTEGER;

CREATE TABLE IF NOT EXISTS reserva_bloque (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reserva_id BIGINT NOT NULL,
    recurso_id BIGINT NOT NULL REFERENCES recurso(id),
    fecha DATE NOT NULL,
    bloque INTEGER NOT NULL CHECK (bloque BETWEEN 0 AND 23),
    CONSTRAINT uq_reserva_bloque_recurso_fecha UNIQUE (recurso_id, fecha, bloque),
    CONSTRAINT fk_reserva_bloque_reserva
        FOREIGN KEY (reserva_id, recurso_id, fecha)
        REFERENCES reserva(id, recurso_id, fecha)
        ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS producto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL UNIQUE,
    precio NUMERIC(10, 2) NOT NULL CHECK (precio >= 0),
    existencias INTEGER NOT NULL DEFAULT 0 CHECK (existencias >= 0),
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS consumo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reserva_id BIGINT NOT NULL REFERENCES reserva(id),
    producto_id BIGINT NOT NULL REFERENCES producto(id),
    cantidad INTEGER NOT NULL CHECK (cantidad > 0),
    precio_unitario NUMERIC(10, 2) NOT NULL CHECK (precio_unitario >= 0),
    fecha TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_reserva_usuario_fecha
    ON reserva (usuario_id, fecha);

CREATE INDEX IF NOT EXISTS idx_reserva_bloque_reserva
    ON reserva_bloque (reserva_id);
